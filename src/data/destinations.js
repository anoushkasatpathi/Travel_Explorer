export function getDestinationById(id) {
  return destinations.find((d) => d.id === id);
}

export const isAbroad = (d) => d.countryCode !== 'IN';

// "Rajasthan" for Indian places, "Île-de-France, France" abroad, "Singapore" for city-states
export function placeLabel(d) {
  if (!isAbroad(d)) return d.location;
  if (d.location === d.name || d.location === d.country) return d.country;
  return `${d.location}, ${d.country}`;
}

// Stage 3: search (name, state or country) + category + region filters, all at once.
export function filterDestinations(list, query, category, region = 'all') {
  const q = query.trim().toLowerCase();
  return list.filter((d) => {
    const matchesCategory = category === 'All' || d.category === category;
    const matchesRegion = region === 'all' || (region === 'abroad' ? isAbroad(d) : !isAbroad(d));
    const matchesQuery =
      q === '' ||
      d.name.toLowerCase().includes(q) ||
      d.location.toLowerCase().includes(q) ||
      d.country.toLowerCase().includes(q);
    return matchesCategory && matchesRegion && matchesQuery;
  });
}

